package dev.abros.anthub.core;
/** Hints describe consequences, never repeat a visible caption. */
public final class UiHelp {
 private UiHelp(){}
 public static String text(String label){
  if(label.startsWith("Прозрачные панели:"))return "Показывать игровой мир сквозь панели AntHub. Сохраняется на этом компьютере.";
  if(label.startsWith("Масштаб GUI Minecraft:"))return "Меняет размер текста и кнопок во всём Minecraft.";
  if(label.startsWith("Второй слой:"))return "Показывает внешний слой только в этом предпросмотре. Сам скин не меняется.";
  if(label.equals("Обычные руки")||label.equals("Тонкие руки"))return "Выберите модель, для которой нарисован PNG: обычные руки — 4 пикселя, тонкие — 3.";
  if(label.startsWith("Напомнить:"))return "Личное напоминание перед событием. Настройка не меняет напоминания других участников.";
  return switch(label){
   case "Ограничить" -> "Этот игрок не сможет отправлять вам приглашения и отклики. Это не блокирует общий чат.";
   case "Архив" -> "Завершённые и закрытые записи этого раздела.";
   case "Корзина" -> "Удалённые записи, доступные для восстановления по вашим правам.";
   case "Убрать место" -> "Удаляет привязку координат. Изменение применится после сохранения записи.";
   case "Отозвать все устройства и сеансы" -> "Завершит активные сеансы. Для следующего входа потребуется повторная авторизация.";
   case "Отменить с причиной…" -> "Остановит голосование без применения наказания. Причина сохранится в истории.";
   case "Передать руководство" -> "Другой участник станет владельцем объединения. Потребуется подтверждение.";
   case "Прочитать всё" -> "Отмечает все уведомления прочитанными, включая не показанные на этой странице.";
   case "Скрыть запись" -> "Убирает запись из публичного списка. Автор получит уведомление с причиной модерации.";
   default -> "";
  };
 }
}
